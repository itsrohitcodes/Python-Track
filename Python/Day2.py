# Day 2

# Input from user
a = int(input())
b = int(input())

# Arithmetic operators
total = a + b
difference = a - b
product = a * b
division = a / b
floor_division = a // b
modulus = a % b

# Print the results
print(f"The sum of {a} and {b} is {total}")
print(f"The difference of {a} and {b} is {difference}")
print(f"The product of {a} and {b} is {product}")
print(f"The division of {a} and {b} is {division}")
print(f"The floor division of {a} and {b} is {floor_division}")
print(f"The modulus of {a} and {b} is {modulus}")