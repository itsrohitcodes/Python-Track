# Input from user
a = int(input())
b = int(input())

# Arithmetic operators
total = a + b
difference = a - b
product = a * b
division = a / b
floor_division = a // b
modulus = a % b

# Print the results
print("The sum of", a, "and", b, "is", total)
print("The difference of", a, "and", b, "is", difference)
print("The product of", a, "and", b, "is", product)
print("The division of", a, "and", b, "is", division)
print("The floor division of", a, "and", b, "is", floor_division)
print("The modulus of", a, "and", b, "is", modulus)   